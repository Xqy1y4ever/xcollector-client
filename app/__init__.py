"""Xcollector 入库客户端：读聊天记录库 → 抽取通知 → 写进后端。

**它不连 QQ。** 这一层的存在是为了让"入库"和"bot"解耦：
[`nt_msg_db_util`](https://github.com/QQBackup/nt_msg_db_util) 把 NTQQ 的
`nt_msg.db` 解密并导出成明文的 `nt_msg_export.db`，本客户端定期读那个库里
新增的群消息，抽取成通知，再用**用户自己的 UserToken** 写进后端。

于是整套部署变成：

    QQ ──▶ NTQQ ──▶ nt_msg_db_util ──▶ nt_msg_export.db ──▶ xcollector-client
                                                                    │
                                                          （UserToken）
                                                                    ▼
                                                            xcollector-backend ◀── xcollector-web

bot 仍然可以做入库（实时性更好），但**不再必需** —— 这正是"后端和 bot 分离"
的意思：后端的数据不再只依赖那一个活的 OneBot 连接。

设计上的几条硬线：

  - **只用 UserToken**。客户端拿的是某个用户自己的令牌，所以它写的每一条数据
    都天然属于那个人，越权在实现上不可能发生。它也**绝不**调用服务令牌专属的
    接口（列用户、发邀请码、投递名单……）。
  - **订阅是过滤条件**。客户端不自己配订阅，而是读后端里这个用户已经配好的
    订阅（网页或 `/订阅` 指令配的）—— 配置只有一份，不会出现"网页上订了但
    客户端不知道"。写共享层时后端还会再校验一次"这个来源是你订的吗"。
  - **不做静默降级**。拿不到附件、抽不出时间、模型挂了，都要留下可查的痕迹
    （通知上的字段 + 统计 + 一行日志），而不是安静地少一条。
"""

